-- ---------- Integrity trigger: 0 <= amount_safe_to_pay <= requested_amount ----------
CREATE FUNCTION trg_check_safe_amount() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.amount_safe_to_pay > (SELECT requested_amount FROM REQUESTS WHERE request_id = NEW.request_id) THEN
    RAISE EXCEPTION 'amount_safe_to_pay % exceeds requested_amount for request %', NEW.amount_safe_to_pay, NEW.request_id;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER decisions_safe_amount BEFORE INSERT OR UPDATE ON DECISIONS
  FOR EACH ROW EXECUTE FUNCTION trg_check_safe_amount();

-- ---------- Views ----------
-- Precedence resolution: one winning record per transaction family (original + its related records)
CREATE VIEW V_EFFECTIVE_EVENTS AS
WITH RECURSIVE fam AS (
  SELECT event_id, event_id AS root_id FROM FINANCIAL_EVENTS WHERE parent_event_id IS NULL
  UNION ALL
  SELECT e.event_id, f.root_id FROM FINANCIAL_EVENTS e JOIN fam f ON e.parent_event_id = f.event_id
), ranked AS (
  SELECT e.*, f.root_id, s.status_rank, s.forecast_rule, sd.source_type, st.source_rank,
         ROW_NUMBER() OVER (PARTITION BY f.root_id
                            ORDER BY s.status_rank, st.source_rank, e.event_id DESC) AS rn
  FROM FINANCIAL_EVENTS e
  JOIN fam f               ON f.event_id = e.event_id
  JOIN EVENT_STATUSES s    ON s.status = e.status
  JOIN SOURCE_DOCUMENTS sd ON sd.source_doc_id = e.source_doc_id
  JOIN SOURCE_TYPES st     ON st.source_type = sd.source_type
)
SELECT event_id, root_id, user_id, event_type, category_id, amount, currency, event_date,
       status, source_type, recurrence_interval
FROM ranked
WHERE rn = 1
  AND forecast_rule <> 'EXCLUDE'
  AND NOT (forecast_rule = 'OUTFLOW_ONLY' AND amount > 0)                       -- pending credits
  AND NOT (event_type = 'INVESTMENT' AND amount > 0 AND status <> 'CLEARED');   -- unrealised investments

CREATE VIEW V_EVENTS_FULL AS
SELECT e.*, sd.source_type, st.source_rank, s.status_rank, s.forecast_rule,
       (e.recurrence_interval IS NOT NULL) AS is_recurring
FROM FINANCIAL_EVENTS e
JOIN SOURCE_DOCUMENTS sd ON sd.source_doc_id = e.source_doc_id
JOIN SOURCE_TYPES st     ON st.source_type   = sd.source_type
JOIN EVENT_STATUSES s    ON s.status         = e.status;

CREATE VIEW V_FORECAST_HEADROOM AS
SELECT f.snapshot_id, f.decision_id, f.forecast_date, f.projected_balance, f.projected_savings,
       f.projected_balance - d.min_threshold_applied AS headroom_above_min
FROM FORECAST_SNAPSHOTS f JOIN DECISIONS d ON d.decision_id = f.decision_id;

-- ---------- Helper: convert an amount into the user's base currency ----------
CREATE FUNCTION fn_to_base(p_amount NUMERIC, p_from CHAR(3), p_to CHAR(3), p_on DATE)
RETURNS NUMERIC LANGUAGE sql STABLE AS $$
  SELECT CASE WHEN p_from = p_to THEN p_amount
         ELSE p_amount * (SELECT rate FROM EXCHANGE_RATES
                          WHERE from_currency = p_from AND to_currency = p_to AND rate_date <= p_on
                          ORDER BY rate_date DESC LIMIT 1) END
$$;

CREATE FUNCTION fn_interval(p VARCHAR) RETURNS INTERVAL LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE p WHEN 'DAILY' THEN INTERVAL '1 day' WHEN 'WEEKLY' THEN INTERVAL '7 days'
                WHEN 'MONTHLY' THEN INTERVAL '1 month' WHEN 'QUARTERLY' THEN INTERVAL '3 months'
                WHEN 'YEARLY' THEN INTERVAL '1 year' END
$$;

-- ---------- 90-day forecast: recursive CTE + window functions ----------
-- Horizon = p_as_of .. p_as_of + 89 (90 days). Opening balance = effective events before p_as_of
-- (recurring templates excluded: they only generate future occurrences).
CREATE FUNCTION fn_forecast_90(p_user INT, p_as_of DATE)
RETURNS TABLE (forecast_date DATE, net_flow NUMERIC, projected_balance NUMERIC,
               projected_savings NUMERIC, headroom_above_min NUMERIC)
LANGUAGE sql STABLE AS $$
WITH RECURSIVE prof AS (
  SELECT currency, min_balance_threshold FROM FINANCIAL_PROFILES WHERE user_id = p_user
), eff AS (
  SELECT * FROM V_EFFECTIVE_EVENTS WHERE user_id = p_user
), opening AS (
  SELECT COALESCE(SUM(fn_to_base(e.amount, e.currency, p.currency, e.event_date)), 0) AS bal
  FROM eff e, prof p
  WHERE e.recurrence_interval IS NULL AND e.event_date < p_as_of
), occ AS (                                   -- expand recurring items across the horizon
  SELECT e.event_id, e.amount, e.currency, e.event_date AS occ_date, e.recurrence_interval
  FROM eff e WHERE e.recurrence_interval IS NOT NULL AND e.event_date <= p_as_of + 89
  UNION ALL
  SELECT o.event_id, o.amount, o.currency, (o.occ_date + fn_interval(o.recurrence_interval))::date, o.recurrence_interval
  FROM occ o WHERE (o.occ_date + fn_interval(o.recurrence_interval))::date <= p_as_of + 89
), flows AS (
  SELECT occ_date AS d, amount, currency FROM occ WHERE occ_date >= p_as_of
  UNION ALL
  SELECT event_date, amount, currency FROM eff
  WHERE recurrence_interval IS NULL AND event_date BETWEEN p_as_of AND p_as_of + 89
), days AS (
  SELECT g::date AS d FROM generate_series(p_as_of, p_as_of + 89, INTERVAL '1 day') g
), daily AS (
  SELECT dy.d, COALESCE(SUM(fn_to_base(f.amount, f.currency, p.currency, LEAST(f.d, p_as_of))), 0) AS net
  FROM days dy CROSS JOIN prof p LEFT JOIN flows f ON f.d = dy.d
  GROUP BY dy.d
)
SELECT d,
       ROUND(net, 2),
       ROUND(o.bal + SUM(net) OVER w, 2),
       ROUND(SUM(net) OVER w, 2),
       ROUND(o.bal + SUM(net) OVER w - (SELECT min_balance_threshold FROM prof), 2)
FROM daily, opening o
WINDOW w AS (ORDER BY d ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW)
ORDER BY d
$$;

-- ---------- Installment schedule of a payment option ----------
CREATE FUNCTION fn_schedule(p_option INT, p_amount NUMERIC, p_start DATE)
RETURNS TABLE (installment_number INT, due_date DATE, installment_amount NUMERIC)
LANGUAGE sql STABLE AS $$
  WITH o AS (SELECT * FROM PAYMENT_OPTIONS WHERE option_id = p_option),
  t AS (SELECT o.*, GREATEST(o.tenure_months, 1) AS n,
               p_amount * (1 + o.interest_rate_bps / 10000.0 * o.tenure_months / 12.0) AS total
        FROM o)
  SELECT k, (p_start + (k - 1) * INTERVAL '1 month')::date,
         ROUND(t.total / t.n + CASE WHEN k = 1 THEN t.processing_fee ELSE 0 END, 2)
  FROM t, generate_series(1, t.n) k
$$;

-- ---------- Audit hash (no personal data enters the hash) ----------
CREATE FUNCTION fn_decision_hash(p_decision INT, p_prev CHAR(64)) RETURNS CHAR(64)
LANGUAGE sql STABLE AS $$
  SELECT encode(sha256(convert_to(concat_ws('|', d.decision_id, d.request_id, d.affordability_status,
         d.amount_safe_to_pay, d.earliest_safe_date, d.chosen_option_id, d.min_threshold_applied,
         d.valid_time_start, d.created_at, COALESCE(p_prev, 'GENESIS')), 'UTF8')), 'hex')
  FROM DECISIONS d WHERE d.decision_id = p_decision
$$;

-- ---------- Decision procedure (process 7.0) ----------
CREATE FUNCTION sp_decide(p_request INT, p_as_of DATE DEFAULT CURRENT_DATE) RETURNS INT
LANGUAGE plpgsql AS $$
DECLARE
  r REQUESTS%ROWTYPE; thr NUMERIC; v_now TIMESTAMPTZ := clock_timestamp();
  v_min_head NUMERIC; v_safe NUMERIC; v_status VARCHAR; v_opt INT; v_earliest DATE;
  v_dec INT; v_prev CHAR(64); v_summary TEXT; v_short NUMERIC;
BEGIN
  SELECT * INTO r FROM REQUESTS WHERE request_id = p_request FOR UPDATE;
  UPDATE REQUESTS SET status = 'EVALUATING' WHERE request_id = p_request;
  SELECT min_balance_threshold INTO thr FROM FINANCIAL_PROFILES WHERE user_id = r.user_id;

  SET LOCAL client_min_messages = warning;
  DROP TABLE IF EXISTS base;
  CREATE TEMP TABLE base ON COMMIT DROP AS SELECT * FROM fn_forecast_90(r.user_id, p_as_of);
  SELECT MIN(headroom_above_min) INTO v_min_head FROM base;
  v_safe := LEAST(r.requested_amount, GREATEST(v_min_head, 0));

  -- Ranking rules: eligible = every day of the 90-day horizon stays >= threshold after the
  -- option's installments; order by plan_type FULL first, then total cost, tenure, option_id.
  SELECT o.option_id INTO v_opt
  FROM PAYMENT_OPTIONS o
  WHERE o.event_id = r.event_id AND o.is_active
    AND NOT EXISTS (
      SELECT 1 FROM base b
      WHERE b.headroom_above_min
            - COALESCE((SELECT SUM(s.installment_amount) FROM fn_schedule(o.option_id, r.requested_amount, p_as_of) s
                        WHERE s.due_date <= b.forecast_date), 0) < 0)
  ORDER BY (o.plan_type = 'FULL') DESC,
           (SELECT SUM(s.installment_amount) FROM fn_schedule(o.option_id, r.requested_amount, p_as_of) s),
           o.tenure_months, o.option_id
  LIMIT 1;

  IF v_opt IS NULL THEN
    v_status := 'WAIT';
    -- earliest day d where paying in full keeps every remaining day of the horizon >= threshold
    SELECT MIN(forecast_date) INTO v_earliest FROM (
      SELECT forecast_date,
             MIN(headroom_above_min) OVER (ORDER BY forecast_date ROWS BETWEEN CURRENT ROW AND UNBOUNDED FOLLOWING) AS future_min
      FROM base) x
    WHERE future_min >= r.requested_amount;
  ELSIF (SELECT plan_type FROM PAYMENT_OPTIONS WHERE option_id = v_opt) = 'FULL' THEN
    v_status := 'SAFE_NOW'; v_earliest := p_as_of;
  ELSE
    v_status := 'SPLIT_PLAN';
    SELECT MAX(due_date) INTO v_earliest FROM fn_schedule(v_opt, r.requested_amount, p_as_of);
  END IF;

  v_summary := CASE v_status
    WHEN 'SAFE_NOW'   THEN format('Pay %s in full today; balance stays above %s for all 90 days.', r.requested_amount, thr)
    WHEN 'SPLIT_PLAN' THEN format('Paying in full would breach the %s minimum; option %s keeps all 90 days safe. Safe to pay today: %s.', thr, v_opt, v_safe)
    ELSE format('No option keeps the 90-day balance above %s. Safe to pay today: %s. Earliest full-payment date: %s.',
                thr, v_safe, COALESCE(v_earliest::text, 'beyond the 90-day horizon')) END;

  -- bitemporal versioning: close the current version, insert the new one
  UPDATE DECISIONS SET valid_time_end = v_now WHERE request_id = p_request AND valid_time_end IS NULL;
  INSERT INTO DECISIONS (request_id, chosen_option_id, affordability_status, amount_safe_to_pay,
                         earliest_safe_date, min_threshold_applied, decision_summary, valid_time_start)
  VALUES (p_request, v_opt, v_status, v_safe, v_earliest, thr, v_summary, v_now)
  RETURNING decision_id INTO v_dec;

  INSERT INTO PLAN_ITEMS (decision_id, installment_number, installment_amount, due_date)
  SELECT v_dec, s.installment_number, s.installment_amount, s.due_date
  FROM fn_schedule(v_opt, r.requested_amount, p_as_of) s WHERE v_opt IS NOT NULL;

  -- 90 snapshots: projection after the chosen plan (or the base projection when WAIT)
  INSERT INTO FORECAST_SNAPSHOTS (decision_id, forecast_date, projected_balance, projected_savings)
  SELECT v_dec, b.forecast_date, b.projected_balance - pay.cum, b.projected_savings - pay.cum
  FROM base b CROSS JOIN LATERAL (
    SELECT COALESCE(SUM(s.installment_amount), 0) AS cum
    FROM fn_schedule(v_opt, r.requested_amount, p_as_of) s
    WHERE v_opt IS NOT NULL AND s.due_date <= b.forecast_date) pay;

  -- spending changes when waiting: cut discretionary categories by at most 50% of their last-30-day
  -- spend, and lengthen the period (in 30-day steps, at most 90 days) towards covering the shortfall
  IF v_status = 'WAIT' THEN
    v_short := r.requested_amount - v_safe;
    INSERT INTO SPENDING_CHANGES (decision_id, category_id, recommended_reduction, period_days)
    SELECT v_dec, category_id, cut, LEAST(90, 30 * CEIL(v_short / SUM(cut) OVER ())::int)   -- never beyond the 90-day horizon
    FROM (SELECT e.category_id, ROUND(LEAST(0.5 * -SUM(e.amount), v_short), 2) AS cut
          FROM V_EFFECTIVE_EVENTS e JOIN CATEGORIES c ON c.category_id = e.category_id
          WHERE e.user_id = r.user_id AND e.amount < 0 AND c.is_discretionary
            AND e.event_date BETWEEN p_as_of - 30 AND p_as_of - 1
          GROUP BY e.category_id) c
    WHERE cut > 0;
  END IF;

  -- seal the decision in the global SHA-256 hash chain
  SELECT current_hash INTO v_prev FROM AUDIT_RECORDS ORDER BY audit_id DESC LIMIT 1;
  INSERT INTO AUDIT_RECORDS (decision_id, previous_hash, current_hash)
  VALUES (v_dec, v_prev, fn_decision_hash(v_dec, v_prev));

  UPDATE REQUESTS SET status = 'DECIDED' WHERE request_id = p_request;
  RETURN v_dec;
END $$;

-- ---------- Audit verification: recompute the chain and flag tampering ----------
CREATE FUNCTION sp_verify_audit_chain() RETURNS INT LANGUAGE plpgsql AS $$
DECLARE a RECORD; v_prev CHAR(64); n INT := 0;
BEGIN
  FOR a IN SELECT * FROM AUDIT_RECORDS ORDER BY audit_id LOOP
    IF a.previous_hash IS DISTINCT FROM v_prev
       OR a.current_hash <> fn_decision_hash(a.decision_id, a.previous_hash) THEN
      UPDATE AUDIT_RECORDS SET tamper_flag = TRUE WHERE audit_id = a.audit_id; n := n + 1;
    END IF;
    v_prev := a.current_hash;
  END LOOP;
  RETURN n;
END $$;
