-- =====================================================================
-- Buy or Wait? : relational tier (PostgreSQL 16)
-- Normalised schema (3NF / BCNF), precedence resolution, 90-day forecast,
-- payment-option ranking and SHA-256 hash-chained audit log.
-- MongoDB holds raw evidence (messages, receipt OCR, ledger files, form
-- submissions); SOURCE_DOCUMENTS.source_doc_id is that document's _id.
-- =====================================================================

-- ---------- Reference (lookup) relations ----------
CREATE TABLE CURRENCIES (
  currency_code CHAR(3) PRIMARY KEY,
  currency_name VARCHAR(50) NOT NULL
);

CREATE TABLE CATEGORIES (
  category_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_name    VARCHAR(50) NOT NULL UNIQUE,
  is_discretionary BOOLEAN NOT NULL DEFAULT TRUE    -- only discretionary spend is ever cut
);

-- Precedence level 1: transaction status (lower rank wins)
CREATE TABLE EVENT_STATUSES (
  status        VARCHAR(20) PRIMARY KEY,
  status_rank   INT NOT NULL UNIQUE,
  forecast_rule VARCHAR(12) NOT NULL CHECK (forecast_rule IN ('INCLUDE','OUTFLOW_ONLY','EXCLUDE'))
);

-- Precedence level 2: source of the record (lower rank wins a tie)
CREATE TABLE SOURCE_TYPES (
  source_type VARCHAR(20) PRIMARY KEY,
  source_rank INT NOT NULL UNIQUE
);

-- ---------- Core relations ----------
CREATE TABLE USERS (
  user_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       VARCHAR(100) NOT NULL,
  email      VARCHAR(150) NOT NULL UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE FINANCIAL_PROFILES (
  profile_id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id                INT NOT NULL UNIQUE,
  currency               CHAR(3) NOT NULL,
  min_balance_threshold  NUMERIC(12,2) NOT NULL CHECK (min_balance_threshold >= 0),
  target_monthly_savings NUMERIC(12,2) NOT NULL CHECK (target_monthly_savings >= 0),
  updated_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
  FOREIGN KEY (user_id)  REFERENCES USERS(user_id),
  FOREIGN KEY (currency) REFERENCES CURRENCIES(currency_code)
);

-- Registry of MongoDB evidence documents that passed the validation gate
CREATE TABLE SOURCE_DOCUMENTS (
  source_doc_id CHAR(24) PRIMARY KEY CHECK (source_doc_id ~ '^[0-9a-f]{24}$'),
  source_type   VARCHAR(20) NOT NULL,
  FOREIGN KEY (source_type) REFERENCES SOURCE_TYPES(source_type)
);

CREATE TABLE FINANCIAL_EVENTS (
  event_id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id             INT NOT NULL,
  event_type          VARCHAR(20) NOT NULL
                      CHECK (event_type IN ('INCOME','EXPENSE','BILL','TRANSFER','INVESTMENT')),
  category_id         INT,
  amount              NUMERIC(12,2) NOT NULL CHECK (amount <> 0),   -- signed: + inflow, - outflow
  currency            CHAR(3) NOT NULL,
  event_date          DATE NOT NULL,
  source_doc_id       CHAR(24) NOT NULL,
  parent_event_id     INT,                                           -- the original this record amends/duplicates/cancels
  status              VARCHAR(20) NOT NULL,
  recurrence_interval VARCHAR(10)
                      CHECK (recurrence_interval IN ('DAILY','WEEKLY','MONTHLY','QUARTERLY','YEARLY')),
  FOREIGN KEY (user_id)         REFERENCES USERS(user_id),
  FOREIGN KEY (category_id)     REFERENCES CATEGORIES(category_id),
  FOREIGN KEY (currency)        REFERENCES CURRENCIES(currency_code),
  FOREIGN KEY (source_doc_id)   REFERENCES SOURCE_DOCUMENTS(source_doc_id),
  FOREIGN KEY (parent_event_id) REFERENCES FINANCIAL_EVENTS(event_id),
  FOREIGN KEY (status)          REFERENCES EVENT_STATUSES(status),
  CHECK (parent_event_id IS NULL OR parent_event_id <> event_id)
);
CREATE INDEX ix_events_user_date ON FINANCIAL_EVENTS (user_id, event_date);
CREATE INDEX ix_events_parent    ON FINANCIAL_EVENTS (parent_event_id);

CREATE TABLE EXCHANGE_RATES (
  rate_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  from_currency CHAR(3) NOT NULL,
  to_currency   CHAR(3) NOT NULL,
  rate          NUMERIC(14,6) NOT NULL CHECK (rate > 0),
  rate_date     DATE NOT NULL,
  UNIQUE (from_currency, to_currency, rate_date),
  FOREIGN KEY (from_currency) REFERENCES CURRENCIES(currency_code),
  FOREIGN KEY (to_currency)   REFERENCES CURRENCIES(currency_code),
  CHECK (from_currency <> to_currency)
);

CREATE TABLE REQUESTS (
  request_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id          INT NOT NULL,
  event_id         INT NOT NULL,              -- prospective expense the request is about
  requested_amount NUMERIC(12,2) NOT NULL CHECK (requested_amount > 0),
  category_id      INT NOT NULL,
  target_deadline  DATE,
  status           VARCHAR(20) NOT NULL DEFAULT 'PENDING'
                   CHECK (status IN ('PENDING','EVALUATING','DECIDED')),
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  FOREIGN KEY (user_id)     REFERENCES USERS(user_id),
  FOREIGN KEY (event_id)    REFERENCES FINANCIAL_EVENTS(event_id),
  FOREIGN KEY (category_id) REFERENCES CATEGORIES(category_id)
);

CREATE TABLE PAYMENT_OPTIONS (
  option_id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id          INT NOT NULL,
  plan_type         VARCHAR(20) NOT NULL CHECK (plan_type IN ('FULL','EMI','BNPL')),
  tenure_months     INT NOT NULL DEFAULT 0 CHECK (tenure_months >= 0),
  interest_rate_bps INT NOT NULL DEFAULT 0 CHECK (interest_rate_bps >= 0),
  processing_fee    NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (processing_fee >= 0),
  is_active         BOOLEAN NOT NULL DEFAULT TRUE,
  FOREIGN KEY (event_id) REFERENCES FINANCIAL_EVENTS(event_id),
  CHECK ((plan_type = 'FULL' AND tenure_months = 0) OR (plan_type <> 'FULL' AND tenure_months > 0))
);

CREATE TABLE DECISIONS (
  decision_id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id            INT NOT NULL,
  chosen_option_id      INT,
  affordability_status  VARCHAR(12) NOT NULL CHECK (affordability_status IN ('SAFE_NOW','SPLIT_PLAN','WAIT')),
  amount_safe_to_pay    NUMERIC(12,2) NOT NULL,
  earliest_safe_date    DATE,
  min_threshold_applied NUMERIC(12,2) NOT NULL,
  decision_summary      TEXT NOT NULL,
  valid_time_start      TIMESTAMPTZ NOT NULL,
  valid_time_end        TIMESTAMPTZ,
  created_at            TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),   -- transaction time
  UNIQUE (request_id, valid_time_start),
  FOREIGN KEY (request_id)       REFERENCES REQUESTS(request_id),
  FOREIGN KEY (chosen_option_id) REFERENCES PAYMENT_OPTIONS(option_id),
  CHECK (amount_safe_to_pay >= 0),
  CHECK (valid_time_end IS NULL OR valid_time_end > valid_time_start),
  CHECK (affordability_status = 'WAIT' OR chosen_option_id IS NOT NULL)
);

CREATE TABLE PLAN_ITEMS (
  plan_item_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  decision_id        INT NOT NULL,
  installment_number INT NOT NULL CHECK (installment_number >= 1),
  installment_amount NUMERIC(12,2) NOT NULL CHECK (installment_amount > 0),
  due_date           DATE NOT NULL,
  status             VARCHAR(10) NOT NULL DEFAULT 'DUE' CHECK (status IN ('DUE','PAID','MISSED')),
  UNIQUE (decision_id, installment_number),
  FOREIGN KEY (decision_id) REFERENCES DECISIONS(decision_id)
);

-- Exactly 90 rows per decision: one per day of the forecast horizon
CREATE TABLE FORECAST_SNAPSHOTS (
  snapshot_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  decision_id       INT NOT NULL,
  forecast_date     DATE NOT NULL,
  projected_balance NUMERIC(14,2) NOT NULL,
  projected_savings NUMERIC(14,2) NOT NULL,
  UNIQUE (decision_id, forecast_date),
  FOREIGN KEY (decision_id) REFERENCES DECISIONS(decision_id)
);

CREATE TABLE SPENDING_CHANGES (
  change_id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  decision_id           INT NOT NULL,
  category_id           INT NOT NULL,
  recommended_reduction NUMERIC(12,2) NOT NULL CHECK (recommended_reduction > 0),
  period_days           INT NOT NULL CHECK (period_days > 0),
  UNIQUE (decision_id, category_id),
  FOREIGN KEY (decision_id) REFERENCES DECISIONS(decision_id),
  FOREIGN KEY (category_id) REFERENCES CATEGORIES(category_id)
);

CREATE TABLE AUDIT_RECORDS (
  audit_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  decision_id   INT NOT NULL UNIQUE,
  previous_hash CHAR(64),
  current_hash  CHAR(64) NOT NULL UNIQUE,
  tamper_flag   BOOLEAN NOT NULL DEFAULT FALSE,
  logged_at     TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
  FOREIGN KEY (decision_id) REFERENCES DECISIONS(decision_id)
);

